#!/usr/bin/env python3
"""Universal Orchestrator Kit — Codex adapter installer (kit 1.0.0).

  python3 UNIVERSAL-ORCHESTRATOR-KIT/adapters/codex/install.py [--project DIR]
          [--models tier1=<model>,tier2=<model>,tier3=<model>,review=<model>] [--dry-run]

Installs, additively and idempotently (backups in .orchestrator/backups/<ts>/):
  - .orchestrator/ working tree, policy files, shared G1 hook (copied before it is registered);
  - .codex/agents/uok_<role>.toml custom agents (name, description, developer_instructions,
    optional model; shell disabled for shell=none roles);
  - .agents/skills/uok/SKILL.md — user launcher: $uok mention (Codex skills are invoked with $,
    not /; custom prompts are deprecated) [verified_doc: learn.chatgpt.com/docs/build-skills];
  - AGENTS.md marked section;
  - PreToolUse hook in .codex/hooks.json (merged; user hooks kept) -> G1 guard --format codex.
Codex specifics [verified_doc: learn.chatgpt.com/docs/hooks, /docs/agent-configuration/subagents]:
project hooks run only after the project `.codex/` layer is trusted and the hook is reviewed with
`/hooks`; PreToolUse cannot ask (the guard denies with a "human must run it" reason instead); hook
input carries no subagent identity; sandbox/approval cannot be set per agent.
Without --models the agents inherit the session model.
"""
import os, sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.realpath(__file__))), "shared"))
import uok_install as core  # noqa: E402

MATCHER = "Bash|apply_patch|Edit|Write|mcp__.*"


def toml_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


class CodexInstaller(core.BaseInstaller):
    HOST, FORMAT, INSTRUCTION_FILE = "codex", "codex", "AGENTS.md"
    SKILL_DIR, SKILL_INVOKE = ".agents/skills/uok", "$uok"

    def __init__(self, *a, **kw):
        super().__init__(*a, **kw)
        self.degradations += [
            "PreToolUse cannot ask: SEC-07 operations are denied with a 'human must run it' reason",
            "hook input has no subagent identity: worker-only rules are instructions, not hook-enforced",
            "sandbox_mode/approval_policy cannot be set per agent: read-only roles rely on instructions; "
            "subagents inherit the session sandbox",
        ]
        if self.mode == "strict":
            self.warnings.append("strict mode has no effect on Codex (no worker identity in hook input)")

    def workers_line(self):
        return ("The main session is the **orchestrator**; workers are the custom agents `uok_<role>` in "
                f"`.codex/agents/` (one per role in `{self.kit_rel}/core/AGENT-CAPABILITIES.yaml`). Delegate by "
                "naming them, e.g. \"Have uok_test_engineer run the tests\".")

    def host_steps(self):
        for r in core.roles():
            tier = "TIER-5" if r["id"] in ("code_reviewer", "security_reviewer") else r["default_tier"]
            model = self.model_for(tier)
            body = core.role_rules(r)
            assert '"""' not in body
            lines = [f"# {core.ROLE_MARK} — generated by install.py; edit the kit, then re-run the installer.",
                     f"name = {toml_str('uok_' + r['id'])}",
                     f"description = {toml_str(r['name'] + ' ' + core.ROLE_MARK + '. Use for: ' + '; '.join(r['responsibilities'][:2]) + '.')}"]
            if model:
                lines.append(f"model = {toml_str(model)}")
            lines.append('developer_instructions = """\n' + body + '"""')
            if r["permissions"]["shell"] == "none":
                lines += ["", "[features]", "shell_tool = false"]
            self.write_managed(self.p(".codex", "agents", f"uok_{r['id']}.toml"), "\n".join(lines) + "\n",
                               f"kit role {r['id']}")
        self.step_instruction_file()

    def register_hook(self):
        cmd = core.hook_command(self.FORMAT)

        def mutate(d):
            groups = d.setdefault("hooks", {}).setdefault("PreToolUse", [])
            groups[:] = [g for g in groups if not any("g1_guard.py" in h.get("command", "") for h in g.get("hooks", []))]
            groups.append({"matcher": MATCHER, "hooks": [{"type": "command", "command": cmd, "timeout": 30,
                                                          "statusMessage": "UOK G1 guard"}]})
        self.merge_json(self.p(".codex", "hooks.json"), mutate, "PreToolUse G1 hook (merged)")

    def smoke_event(self):
        return ({"tool_name": "apply_patch", "cwd": self.root,
                 "tool_input": {"command": "*** Begin Patch\n*** Add File: .env\n+X=1\n*** End Patch"}}, '"deny"')

    def next_steps(self):
        return ("next: open the project in Codex, trust the project `.codex/` layer, review and trust the G1 hook with "
                "`/hooks`, then run the live checks in the adapter README and fill "
                f"{self.kit_rel}/handoff/INSTALLATION-REPORT-TEMPLATE.md. "
                "Launch orchestration with the `$uok` skill mention.")


if __name__ == "__main__":
    core.cli(CodexInstaller, __doc__)
